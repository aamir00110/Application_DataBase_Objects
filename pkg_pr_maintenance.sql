create or replace PACKAGE BODY PKG_PR_MAINTENANCE AS

    PROCEDURE INSERT_PM_PLAN (
        -- P_PLAN_ID              IN MS_PM_PLAN_H.PLAN_ID%TYPE,
        P_PLAN_NO              IN MS_PM_PLAN_H.PLAN_NO%TYPE,
        P_PLAN_NAME            IN MS_PM_PLAN_H.PLAN_NAME%TYPE,
        P_HALL_ID              IN MS_PM_PLAN_H.HALL_ID%TYPE,
        P_LINE_ID              IN MS_PM_PLAN_H.LINE_ID%TYPE,
        P_MACHINE_ID           IN MS_PM_PLAN_H.MACHINE_ID%TYPE,
        P_FREQUENCY_ID         IN MS_PM_PLAN_H.FREQUENCY_ID%TYPE,
        P_START_DATE           IN MS_PM_PLAN_H.START_DATE%TYPE,
        P_END_DATE             IN MS_PM_PLAN_H.END_DATE%TYPE,
        P_NEXT_DUE_DATE        IN MS_PM_PLAN_H.NEXT_DUE_DATE%TYPE,
        P_ASSIGNED_TO          IN MS_PM_PLAN_H.ASSIGNED_TO%TYPE,
        P_PRIORITY             IN MS_PM_PLAN_H.PRIORITY%TYPE,
        P_PLAN_DESCRIPTION     IN MS_PM_PLAN_H.PLAN_DESCRIPTION%TYPE,
        P_STATUS_CODE          IN MS_PM_PLAN_H.STATUS_CODE%TYPE,
        P_ACTIVE_YN            IN MS_PM_PLAN_H.ACTIVE_YN%TYPE,
        P_CUSTOM_INTERVAL_DAYS IN MS_PM_PLAN_H.CUSTOM_INTERVAL_DAYS%TYPE
    )
    IS
    BEGIN
        INSERT INTO MS_PM_PLAN_H (
            -- PLAN_ID, 
    PLAN_NO, PLAN_NAME, HALL_ID, LINE_ID, MACHINE_ID,FREQUENCY_ID, START_DATE, END_DATE, NEXT_DUE_DATE, ASSIGNED_TO,
    PRIORITY, PLAN_DESCRIPTION, STATUS_CODE, ACTIVE_YN,CUSTOM_INTERVAL_DAYS     ) 
VALUES (
            -- P_PLAN_ID, 
    P_PLAN_NO, P_PLAN_NAME, P_HALL_ID, P_LINE_ID, P_MACHINE_ID,P_FREQUENCY_ID, P_START_DATE, P_END_DATE,NVL(P_NEXT_DUE_DATE, P_START_DATE),P_ASSIGNED_TO, 
    P_PRIORITY, P_PLAN_DESCRIPTION, P_STATUS_CODE,NVL(P_ACTIVE_YN, 'Y'),P_CUSTOM_INTERVAL_DAYS);
    
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20001, 'Plan already exists (duplicate PLAN_ID / PLAN_NO).');
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(-20002, 'INSERT_PM_PLAN failed: ' || SQLERRM);
    END INSERT_PM_PLAN;

END PKG_PR_MAINTENANCE;
